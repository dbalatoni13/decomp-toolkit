//! Minimal PS3 PPU ELF model used by the split generator.

use std::{
    collections::BTreeMap,
    ops::{Index, IndexMut},
};

use flagset::{FlagSet, flags};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ObjKind {
    Executable,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ObjArchitecture {
    PowerPc64,
}

#[derive(Debug, Clone)]
pub struct ObjUnit {
    pub name: String,
    #[allow(dead_code)] // DTK metadata retained for generated split tests and editing.
    pub autogenerated: bool,
    pub comment_version: Option<u8>,
    pub order: Option<i32>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ObjSectionKind {
    Code,
    Data,
    ReadOnlyData,
    Bss,
}

#[derive(Debug, Clone)]
pub struct ObjSection {
    pub name: String,
    pub kind: ObjSectionKind,
    pub address: u64,
    pub size: u64,
    pub data: Vec<u8>,
    pub align: u64,
    pub elf_index: u32,
    pub splits: ObjSplits,
}

#[derive(Debug, Clone, Default)]
pub struct ObjSplits(BTreeMap<u32, Vec<ObjSplit>>);

impl ObjSplits {
    pub fn iter(&self) -> impl DoubleEndedIterator<Item = (u32, &ObjSplit)> {
        self.0.iter().flat_map(|(&address, splits)| splits.iter().map(move |s| (address, s)))
    }

    pub fn push(&mut self, address: u32, split: ObjSplit) {
        self.0.entry(address).or_default().push(split);
    }

    pub fn clear(&mut self) { self.0.clear(); }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ObjSplit {
    pub unit: String,
    pub end: u32,
    pub align: Option<u32>,
    pub common: bool,
    pub autogenerated: bool,
    pub skip: bool,
    pub rename: Option<String>,
}

#[derive(Debug, Clone)]
pub struct ObjSections(Vec<ObjSection>);

impl ObjSections {
    pub fn iter(&self) -> impl DoubleEndedIterator<Item = (u32, &ObjSection)> {
        self.0.iter().enumerate().map(|(i, s)| (i as u32, s))
    }

    pub fn get(&self, index: u32) -> Option<&ObjSection> { self.0.get(index as usize) }

    pub fn get_mut(&mut self, index: u32) -> Option<&mut ObjSection> {
        self.0.get_mut(index as usize)
    }
}

impl Index<u32> for ObjSections {
    type Output = ObjSection;

    fn index(&self, index: u32) -> &Self::Output { &self.0[index as usize] }
}

impl IndexMut<u32> for ObjSections {
    fn index_mut(&mut self, index: u32) -> &mut Self::Output { &mut self.0[index as usize] }
}

flags! {
    #[repr(u32)]
    pub enum ObjSymbolFlags: u32 { Global, Local, Weak }
}

#[derive(Debug, Clone, Copy, Default)]
pub struct ObjSymbolFlagSet(pub FlagSet<ObjSymbolFlags>);

impl ObjSymbolFlagSet {
    pub fn is_local(self) -> bool { self.0.contains(ObjSymbolFlags::Local) }

    pub fn is_weak(self) -> bool { self.0.contains(ObjSymbolFlags::Weak) }
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum ObjSymbolKind {
    #[default]
    Unknown,
    Function,
    Object,
    Section,
}

#[derive(Debug, Clone, Default)]
pub struct ObjSymbol {
    pub name: String,
    pub address: u64,
    pub section: Option<u32>,
    pub size: u64,
    pub size_known: bool,
    pub flags: ObjSymbolFlagSet,
    pub kind: ObjSymbolKind,
    pub align: Option<u32>,
}

#[derive(Debug, Clone)]
pub struct ObjSymbols(Vec<ObjSymbol>);

impl ObjSymbols {
    pub fn len(&self) -> usize { self.0.len() }

    pub fn is_empty(&self) -> bool { self.0.is_empty() }

    pub fn iter(&self) -> impl DoubleEndedIterator<Item = (u32, &ObjSymbol)> {
        self.0.iter().enumerate().map(|(i, s)| (i as u32, s))
    }

    pub fn iter_mut(&mut self) -> impl Iterator<Item = &mut ObjSymbol> { self.0.iter_mut() }

    pub fn get(&self, id: u32) -> Option<&ObjSymbol> { self.0.get(id as usize) }

    pub fn get_mut(&mut self, id: u32) -> Option<&mut ObjSymbol> { self.0.get_mut(id as usize) }

    pub fn push(&mut self, symbol: ObjSymbol) { self.0.push(symbol); }
}

#[derive(Debug, Clone)]
pub struct ObjInfo {
    pub symbols: ObjSymbols,
    pub sections: ObjSections,
    pub entry: Option<u64>,
    pub link_order: Vec<ObjUnit>,
}

impl ObjInfo {
    pub fn new(
        _kind: ObjKind,
        _architecture: ObjArchitecture,
        _name: String,
        symbols: Vec<ObjSymbol>,
        sections: Vec<ObjSection>,
    ) -> Self {
        Self {
            symbols: ObjSymbols(symbols),
            sections: ObjSections(sections),
            entry: None,
            link_order: Vec::new(),
        }
    }
}
